const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const base = pathToFileURL(path.resolve('index.html')).href;
    const go = async route => {
      await page.goto(`${base}#${route}`);
      await page.locator('#screen').waitFor();
      await page.waitForFunction(r => document.querySelector('#screen').dataset.route === r, route);
    };
    await go('inicio');
    await page.evaluate(() => sessionStorage.clear());

    await go('portfolio');
    await page.locator('[data-skill-level="Organização"]').selectOption('5');
    assert.match(await page.locator('#portfolio-live .pf-skills').innerText(), /Organização\s+5\/5/);
    await page.reload();
    assert.equal(await page.locator('[data-skill-level="Organização"]').inputValue(), '5');
    await page.locator('[data-action="edit-project"]').click();
    await page.locator('#project-title').fill('Mutirão de leitura');
    await page.locator('#project-where').fill('Biblioteca da escola');
    await page.locator('#project-role').fill('Coordenação das inscrições');
    await page.locator('#project-process').fill('Organizei horários, registrei participantes e distribuí as tarefas com a equipe.');
    await page.locator('#project-result').fill('Aprendi a ajustar o cronograma com o grupo.');
    await page.locator('#project-form button[type="submit"]').click();
    assert.equal(await page.locator('.project-management .project-details h3').innerText(), 'Mutirão de leitura');
    assert.match(await page.locator('#portfolio-live .pf-project').innerText(), /Biblioteca da escola/);
    await page.reload();
    assert.equal(await page.locator('.project-management .project-count').innerText(), '1 de 1');
    assert.match(await page.locator('#portfolio-live .pf-project').innerText(), /Coordenação das inscrições/);
    await page.locator('[data-visibility="projects"]').uncheck();
    assert.equal(await page.locator('#portfolio-live .pf-project').count(), 0);
    await page.locator('[data-visibility="projects"]').check();
    await page.locator('[data-action="preview"]').first().click();
    assert.match(await page.locator('#dialog .pf-project').innerText(), /Mutirão de leitura/);
    await page.locator('#dialog [data-action="close-modal"]').click();
    await page.locator('[data-action="remove-project"]').click();
    await page.locator('#dialog .form-actions [data-action="close-modal"]').click();
    assert.equal(await page.locator('.project-management .project-count').innerText(), '1 de 1');
    await page.locator('[data-action="remove-project"]').click();
    await page.locator('#dialog [data-action="confirm-remove-project"]').click();
    assert.equal(await page.locator('#portfolio-live .pf-project').count(), 0);
    await page.reload();
    assert.equal(await page.locator('.project-management .project-count').innerText(), '0 de 1');
    await page.locator('[data-action="edit-project"]').click();
    await page.locator('#project-title').fill('Oficina de escrita');
    await page.locator('#project-where').fill('Centro comunitário');
    await page.locator('#project-role').fill('Facilitação');
    await page.locator('#project-process').fill('Preparei atividades e acompanhei a produção de textos.');
    await page.locator('#project-form button[type="submit"]').click();
    assert.equal(await page.locator('.project-management .project-details').count(), 1);
    fs.mkdirSync('tmp/qa', {recursive:true});
    await page.reload();
    await page.screenshot({path:'tmp/qa/features-portfolio.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'tmp/qa/features-project-mobile.png',fullPage:true});
    await page.setViewportSize({width:1280,height:900});

    await go('avaliacao/maria');
    assert.match(await page.locator('.company-project').innerText(), /Onde\s+Escola/i);
    assert.match(await page.locator('.company-project').innerText(), /Como fiz/i);

    await go('desafio/marketing');
    assert.match(await page.locator('.challenge-timer').innerText(), /90 min/);
    await page.locator('#colleague-toggle').click();
    assert.equal(await page.locator('#colleague-toggle').getAttribute('aria-expanded'), 'true');
    assert.match(await page.locator('#colleague-title').innerText(), /Roberto/);
    assert.match(await page.locator('.colleague-header').innerText(), /Assistente de marketing II/);
    await page.locator('#colleague-input').fill('Onde encontro os materiais?');
    await page.locator('#colleague-form button').click();
    assert.match(await page.locator('.colleague-message.theirs').last().innerText(), /Custos e resultados por canal/);
    await page.reload();
    await page.locator('#colleague-toggle').click();
    assert.equal(await page.locator('.colleague-message').count(), 3);
    await page.locator('#colleague-input').fill('O que será avaliado?');
    await page.locator('#colleague-input').press('Enter');
    assert.match(await page.locator('.colleague-message.theirs').last().innerText(), /Orçamento/);
    await page.setViewportSize({width:390,height:844});
    const popupBox = await page.locator('#colleague-popup').boundingBox();
    assert(popupBox.x >= 0 && popupBox.x + popupBox.width <= 390);
    await page.screenshot({path:'tmp/qa/features-colleague-mobile.png',fullPage:true});
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#colleague-toggle').getAttribute('aria-expanded'), 'false');
    await page.setViewportSize({width:1280,height:900});
    const answer = '**Plano de campanha:** usaria os dados do anexo para comparar os canais, reservaria R$ 300 para ajustes e mediria visitas registradas no caixa.\n\n| Canal | Verba |\n| --- | --- |\n| Instagram | R$ 1.200 |';
    await page.locator('#response').fill(answer);
    await page.locator('[data-md-view="preview"][data-for="response"]').click();
    assert.match(await page.locator('[data-md-preview="response"] strong').innerText(), /Plano de campanha/);
    assert.equal(await page.locator('[data-md-preview="response"] table tbody tr').count(), 1);
    await page.locator('[data-answer="channel"]').selectOption('Instagram local');
    await page.reload();
    assert.equal(await page.locator('#response').inputValue(), answer);
    assert.equal(await page.locator('[data-answer="channel"]').inputValue(), 'Instagram local');
    await page.locator('#delivery-form button[type="submit"]').click();
    assert.match(await page.locator('.success-banner').innerText(), /Entrega enviada/);
    await go('portfolio');
    await page.locator('[data-share="marketing"]').check();
    await page.locator('#portfolio-live .pf-work-card details').first().click();
    assert.match(await page.locator('#portfolio-live .pf-answer strong').innerText(), /Plano de campanha/);

    await go('criar');
    await page.locator('[data-action="add-question"]').click();
    await page.locator('[data-q-field="label"]').fill('Qual opção você recomenda?');
    await page.locator('[data-q-field="type"]').selectOption('select');
    await page.locator('[data-q-field="options"]').fill('Opção A\nOpção B');
    await page.locator('[data-q-field="required"]').check();
    await page.locator('#draft-time-limit').fill('30');
    await page.locator('#draft-scenario').fill('## Contexto\nAvalie os materiais e explique sua decisão.');
    await page.locator('[data-md-view="preview"][data-for="draft-scenario"]').click();
    assert.match(await page.locator('[data-md-preview="draft-scenario"] h4').innerText(), /Contexto/);
    await page.locator('#briefing-form button[type="submit"]').click();
    assert.equal(await page.locator('#draft-status').innerText(), 'Rascunho salvo');
    await page.reload();
    assert.equal(await page.locator('#draft-time-limit').inputValue(), '30');
    assert.equal(await page.locator('[data-q-field="options"]').inputValue(), 'Opção A\nOpção B');
    await page.screenshot({path:'tmp/qa/features-builder.png',fullPage:true});
    await page.locator('a[href="#desafio/criado"]').click();
    assert.match(await page.locator('.preview-notice').innerText(), /não foi publicada/);
    assert.match(await page.locator('.challenge-timer').innerText(), /30 min/);
    assert.equal(await page.locator('[data-answer] option').count(), 3);
    assert.equal(await page.locator('[data-answer]').getAttribute('required'), '');
    assert.equal(await page.locator('[data-answer]').evaluate(e => e.checkValidity()), false);
    await page.evaluate(() => {
      const saved = JSON.parse(sessionStorage.getItem('hai-v2'));
      saved.deliveries.criado.startedAt = Date.now() - 31 * 60000;
      sessionStorage.setItem('hai-v2', JSON.stringify(saved));
    });
    await page.reload();
    assert.match(await page.locator('.challenge-timer').innerText(), /Tempo encerrado/);
    assert.equal(await page.locator('#delivery-form button[type="submit"]').isDisabled(), true);
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'tmp/qa/features-challenge-mobile.png',fullPage:true});
    await page.evaluate(() => {
      const saved = JSON.parse(sessionStorage.getItem('hai-v2'));
      saved.draft.title = '<img src=x onerror=alert(1)>';
      saved.draft.rubric = 'Critério: <img src=x onerror=alert(1)>';
      sessionStorage.setItem('hai-v2', JSON.stringify(saved));
    });
    await page.reload();
    assert.equal(await page.locator('.page-heading img, .criterion img').count(), 0);
    assert.match(await page.locator('.page-heading h1').innerText(), /<img src=x/);
    await go('desafio/operacoes');
    await page.locator('#colleague-toggle').click();
    assert.match(await page.locator('.colleague-header').innerText(), /Assistente administrativo II/);
    assert.equal(await page.locator('.colleague-message').count(), 1);
    const legacy = await browser.newPage();
    await legacy.goto(`${base}#inicio`);
    await legacy.evaluate(() => sessionStorage.setItem('hai-v2', JSON.stringify({profile:{project:'Projeto antigo',projectDescription:'Organizei as atividades.',institution:'Escola oculta'}})));
    await legacy.goto(`${base}#portfolio`);
    await legacy.reload();
    assert.match(await legacy.locator('#portfolio-live .pf-project').innerText(), /Projeto antigo/);
    assert.doesNotMatch(await legacy.locator('#portfolio-live .pf-project').innerText(), /Escola oculta/);
    await legacy.close();
    assert.equal(errors.length, 0, errors.join('\n'));
    console.log('PASS — Markdown, formulário, tempo limite, conversa com Roberto, competências e projeto único.');
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
